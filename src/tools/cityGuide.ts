/**
 * Food Spot — shareable city guide.
 *
 * Turns the library into a markdown document someone else can read: one
 * section per cuisine, visited places first, your own note as the one-line
 * verdict. Deliberately free of vault/Obsidian imports — everything it needs
 * arrives in the arguments, so the format stays testable on its own.
 */
import type { FoodSpot } from "../types";
import { todayIso } from "../util/dates";

export interface CityGuideOptions {
  includeWantToTry: boolean;
  /** Symbol repeated for the price tier, e.g. "€". */
  currency: string;
}

/** Cuisine-less spots collect here, always last. */
const OTHER_GROUP = "Other";
/** A note longer than this is cut — the guide is a teaser, not the archive. */
const NOTE_MAX = 160;

function sameCity(spot: FoodSpot, city: string): boolean {
  return (spot.city ?? "").trim().toLowerCase() === city.trim().toLowerCase();
}

/** Half-step stars, e.g. 4.5 -> "★★★★½". */
export function starsFor(rating: number): string {
  const full = Math.floor(rating);
  return "★".repeat(full) + (rating - full >= 0.5 ? "½" : "");
}

/** First non-empty line of the note, whitespace-collapsed and length-capped. */
export function firstNoteLine(notes: string): string {
  const line = notes
    .split("\n")
    .map((l) => l.trim())
    .find((l) => l !== "");
  if (line === undefined) return "";
  const flat = line.replace(/\s+/g, " ");
  return flat.length > NOTE_MAX ? `${flat.slice(0, NOTE_MAX - 1).trimEnd()}…` : flat;
}

/** Link text must not break out of the [..](..) it sits in. */
function escapeLinkText(name: string): string {
  return name.replace(/([[\]])/g, "\\$1");
}

function groupOf(spot: FoodSpot): string {
  const first = spot.cuisines.find((c) => c.trim() !== "");
  return first === undefined ? OTHER_GROUP : first.trim();
}

/** Visited first, then best-rated, then alphabetical — unrated spots last. */
function compareSpots(a: FoodSpot, b: FoodSpot): number {
  const visited = Number(b.status === "visited") - Number(a.status === "visited");
  if (visited !== 0) return visited;
  const ra = a.rating ?? -1;
  const rb = b.rating ?? -1;
  if (ra !== rb) return rb - ra;
  return a.name.localeCompare(b.name);
}

function summaryLine(spots: FoodSpot[]): string {
  const visited = spots.filter((s) => s.status === "visited").length;
  const counts = new Map<string, number>();
  for (const spot of spots) {
    for (const cuisine of spot.cuisines) {
      const key = cuisine.trim();
      if (key === "") continue;
      counts.set(key, (counts.get(key) ?? 0) + 1);
    }
  }
  const top = [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, 3)
    .map(([name]) => name);
  const parts = [
    `${spots.length} spot${spots.length === 1 ? "" : "s"}`,
    `${visited} visited`,
  ];
  if (top.length > 0) parts.push(`mostly ${top.join(", ")}`);
  return parts.join(" · ");
}

function entryLine(spot: FoodSpot, opts: CityGuideOptions): string {
  const name = escapeLinkText(spot.name);
  const head =
    spot.url !== undefined && spot.url !== ""
      ? `**[${name}](${spot.url})**`
      : `**${name}**`;
  const bits: string[] = [];
  if (spot.price !== undefined && spot.price > 0) {
    bits.push(opts.currency.repeat(Math.min(4, spot.price)));
  }
  if (spot.rating !== undefined) bits.push(starsFor(spot.rating));
  const google = spot.external.googleRating;
  if (google !== undefined) bits.push(`Google ${google.toFixed(1)}`);
  if (spot.district !== undefined && spot.district.trim() !== "") {
    bits.push(spot.district.trim());
  }
  const note = firstNoteLine(spot.notes);
  const meta = bits.length > 0 ? ` — ${bits.join(" · ")}` : "";
  return `- ${head}${meta}${note === "" ? "" : ` — ${note}`}`;
}

/**
 * Render the guide for one city. Spots from other cities are ignored, so the
 * caller can hand over the whole library.
 */
export function buildCityGuide(
  spots: FoodSpot[],
  city: string,
  opts: CityGuideOptions,
): string {
  const title = city.trim() === "" ? "Eating out" : `Eating in ${city.trim()}`;
  const selected = spots.filter(
    (s) => sameCity(s, city) && (opts.includeWantToTry || s.status === "visited"),
  );
  const footer = `Generated by Food Spot on ${todayIso()}`;

  if (selected.length === 0) {
    const what = opts.includeWantToTry ? "spots" : "visited spots";
    return [`# ${title}`, "", `No ${what} here yet.`, "", footer, ""].join("\n");
  }

  const groups = new Map<string, FoodSpot[]>();
  for (const spot of selected) {
    const key = groupOf(spot);
    const bucket = groups.get(key);
    if (bucket) bucket.push(spot);
    else groups.set(key, [spot]);
  }
  // Biggest cuisine first — it is what the city is known for to you; the
  // catch-all group never outranks a real cuisine.
  const ordered = [...groups.entries()].sort((a, b) => {
    if ((a[0] === OTHER_GROUP) !== (b[0] === OTHER_GROUP)) {
      return a[0] === OTHER_GROUP ? 1 : -1;
    }
    return b[1].length - a[1].length || a[0].localeCompare(b[0]);
  });

  const lines: string[] = [`# ${title}`, "", summaryLine(selected), ""];
  for (const [cuisine, members] of ordered) {
    lines.push(`## ${cuisine}`, "");
    for (const spot of [...members].sort(compareSpots)) {
      lines.push(entryLine(spot, opts));
    }
    lines.push("");
  }
  lines.push(footer, "");
  return lines.join("\n");
}
